class SymbiosisCivilizationEngine:
    def __init__(self):

        self.partnerships = []

    def initialize(self):

        return {
            "system": "aletheus_symbiosis_civilization",
            "range": "9751-9850",
            "status": "operational",
        }

    def create_partnership(self, intent):

        partnership = {"intent": intent, "status": "collaborative"}

        self.partnerships.append(partnership)

        return partnership

    def list_partnerships(self):

        return self.partnerships
